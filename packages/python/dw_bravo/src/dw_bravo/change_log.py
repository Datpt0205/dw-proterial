"""Bravo's own change log, read as saves (ticket 69, the write shadow).

Every save of a document is logged by Bravo's trigger (`DML_<table>_ChangeLog`,
generated by its `_CreateTriggerLog`) into `<db>_Log.dbo.<table>$0`, one row
per row written: the screen and the command word the client put in the
connection's context (`__$CommandKey`, `__$CommandKey0`), I/U/D, the Bravo
user, the time (UTC), the session (one save), and `__$Value`: for an insert
the new row, for a delete the old row, for an update the updated columns'
new values then their old values, as `FOR XML AUTO` elements `new` and
`old` (measured on the production schema, 2026-11-25).

`group_saves` puts the rows of one session on one document together and
classes the save by what it changed, in the terms of DW's write kinds (a
create, a date, a quantity, a price, a split, a cancel), so the shadow
replays each through the rule runner and compares it with what Bravo wrote.
Nothing here reads Bravo: the gateway reads the log, this decides what a
save was.
"""

from __future__ import annotations

import xml.etree.ElementTree as ET
from collections.abc import Iterable, Mapping
from dataclasses import dataclass, field
from datetime import datetime
from typing import Final, Literal

__all__ = ["LogRow", "LoggedLine", "LoggedSave", "SaveKind", "group_saves", "parse_value"]

RowKind = Literal["I", "U", "D"]
SaveKind = Literal[
    "create", "date", "quantity", "price", "split", "cancel", "delete", "touch", "other"
]

# Columns every save rewrites: they say nothing about what the person did.
AUDIT: Final = frozenset({"ModifiedBy", "ModifiedAt", "timestamp"})
# An SO line's dates a person sets (and those the screen computes from them).
DATES: Final = frozenset(
    {
        "EstimatedTimeDelivery",
        "CDDate",
        "SalesAccountingDate",
        "LatestConfirmedDate",
        "OriginalConfirmedDate",
        "PCConfirmDate",
        "SalesReviseDate",
        "HCVCommitDate",
    }
)
# A line's quantity and what the screen computes from it.
QUANTITIES: Final = frozenset(
    {
        "Quantity",
        "Quantity9",
        "Amount",
        "Amount9",
        "OriginalAmount",
        "OriginalAmount9",
        "BoxQuantity",
    }
)
# A line's unit price; its amounts follow it.
PRICES: Final = frozenset({"OriginalUnitCost", "UnitCost"})
CANCELS: Final = frozenset({"IsCancel", "CancelDate"})
CREATES: Final = frozenset({"New", "NewAsCopy", "Import"})


@dataclass(frozen=True)
class LogRow:
    """One row of a `<table>$0` log table."""

    table: str
    command: str
    word: str | None
    kind: RowKind
    user: int | None
    at: datetime
    session: str
    doc_id: str
    row_id: object
    value: str


@dataclass(frozen=True)
class LoggedLine:
    """One row a save wrote: the new and old values of what it changed."""

    row_id: object
    kind: RowKind
    new: Mapping[str, str]
    old: Mapping[str, str]


@dataclass(frozen=True)
class LoggedSave:
    """One save: a session's rows on one document, classed."""

    session: str
    doc_id: str
    command: str
    word: str | None
    user: int | None
    at: datetime
    kind: SaveKind
    lines: tuple[LoggedLine, ...] = field(default=())

    @property
    def changed(self) -> frozenset[str]:
        """The columns the save changed on an updated row, audit left out."""
        return (
            frozenset(c for line in self.lines if line.kind == "U" for c in (*line.new, *line.old))
            - AUDIT
        )


def parse_value(value: str) -> tuple[dict[str, str], dict[str, str]]:
    """The new and the old values a log row holds. Refuses anything that is
    not the trigger's own `new`/`old` elements (a DOCTYPE fails to parse)."""
    text = (value or "").strip()
    if not text:
        return {}, {}
    try:
        # Wrapped in an element, a DOCTYPE is a parse error (no entity is
        # ever declared); ElementTree fetches no external entity.
        root = ET.fromstring(f"<v>{text}</v>")  # nosec B314
    except ET.ParseError as exc:
        raise ValueError(f"a change-log value is not the trigger's XML: {exc}") from None
    new: dict[str, str] = {}
    old: dict[str, str] = {}
    for element in root:
        if element.tag == "new":
            new.update(element.attrib)
        elif element.tag == "old":
            old.update(element.attrib)
        else:
            raise ValueError(f"a change-log value holds <{element.tag}>")
    return new, old


def _kind(word: str | None, lines: list[LoggedLine]) -> SaveKind:
    kinds = {line.kind for line in lines}
    changed = (
        frozenset(c for line in lines if line.kind == "U" for c in (*line.new, *line.old)) - AUDIT
    )
    if kinds == {"I"} and word in CREATES:
        return "create"
    if "I" in kinds and "U" in kinds:
        return "split"
    if "D" in kinds:
        return "delete"
    if changed & CANCELS:
        return "cancel"
    if not changed:
        return "touch"
    if changed <= DATES:
        return "date"
    if changed & PRICES and changed <= PRICES | QUANTITIES:
        return "price"
    if changed <= QUANTITIES | DATES:
        return "quantity"
    return "other"


def group_saves(rows: Iterable[LogRow]) -> list[LoggedSave]:
    """The saves the rows make, one per session and document, oldest first."""
    groups: dict[tuple[str, str], list[LogRow]] = {}
    for row in rows:
        groups.setdefault((row.session, row.doc_id), []).append(row)
    saves = []
    for (session, doc_id), members in groups.items():
        members.sort(key=lambda r: r.at)
        lines = []
        for member in members:
            new, old = parse_value(member.value)
            lines.append(LoggedLine(member.row_id, member.kind, new, old))
        first = members[0]
        saves.append(
            LoggedSave(
                session=session,
                doc_id=doc_id,
                command=first.command,
                word=first.word,
                user=first.user,
                at=first.at,
                kind=_kind(first.word, lines),
                lines=tuple(lines),
            )
        )
    return sorted(saves, key=lambda s: (s.at, s.session, s.doc_id))
